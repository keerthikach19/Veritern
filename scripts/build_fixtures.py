"""Regenerate the frozen synthetic rule-regression corpus (never a model benchmark).

Entire scenario families are assigned to one split; amount variants stay together.
Ground truth is the explicit expected rule catalog below, not generated by assess().
"""

import hashlib
import json
from datetime import date
from pathlib import Path

from veritern.demo import fact
from veritern.schemas import Case, Entity, Program
from veritern.schemas import FactKind as K

ROOT = Path(__file__).resolve().parents[1]

FAMILIES = {
    "development": [
        "free_then_fee",
        "optional_disclosed",
        "missing_terms",
        "tasks",
        "conditional",
        "mentorship",
        "partner",
        "unpaid_unknown",
        "unpaid_due",
        "training",
    ],
    "heldout": [
        "sensitive",
        "authority",
        "referral_hidden",
        "promotion_hidden",
        "pressure",
        "business_test",
        "changed_terms",
        "batch_mismatch",
        "benefit_mismatch",
        "ocr_unreviewed",
    ],
}
EXPECTED = {
    "free_then_fee": ["FEE01"],
    "optional_disclosed": ["FEE03"],
    "missing_terms": ["FEE02"],
    "tasks": ["EXP01"],
    "conditional": ["PAY00"],
    "mentorship": ["EXP02"],
    "partner": ["PART01"],
    "unpaid_unknown": ["PAY03"],
    "unpaid_due": ["PAY02"],
    "training": [],
    "sensitive": ["PRIV01"],
    "authority": ["ID01"],
    "referral_hidden": ["REF01"],
    "promotion_hidden": ["PROMO01"],
    "pressure": ["PRESS01"],
    "business_test": ["WORK01"],
    "changed_terms": ["CHANGE01"],
    "batch_mismatch": ["FEE02"],
    "benefit_mismatch": ["FEE02"],
    "ocr_unreviewed": [],
}


def build(family, variant):
    case = Case(
        owner="fictional-evaluation",
        original_input="Fictional " + family,
        entity=Entity(
            name=f"Fictional {family} {variant}",
            domain=f"{family.replace('_', '-')}-{variant}.test",
        ),
        program=Program(title="Web Development Internship", batch="October 2026"),
        mode="demo",
    )
    amount = [50, 125, 999][variant]
    if family in ("free_then_fee", "batch_mismatch", "benefit_mismatch", "ocr_unreviewed"):
        fact(
            case,
            K.NO_FEE,
            "October 2026 advertisement dated 2026-10-01: every graduate receives a free certificate.",
            event_date=date(2026, 10, 1),
            benefit="certificate",
        )
        fee = fact(
            case,
            K.FEE,
            f"October 2026 message dated 2026-10-09: you must pay INR {amount} to release the certificate.",
            event_date=date(2026, 10, 9),
            amount_minor=amount * 100,
            currency="INR",
            mandatory=True,
            benefit="certificate",
            attribution="participant_reported",
        )
        if family == "batch_mismatch":
            fee.batch = "September 2025"
        if family == "benefit_mismatch":
            fee.benefit = "completion"
        if family == "ocr_unreviewed":
            case.sources[-1].ocr_review_required = True
    elif family == "optional_disclosed":
        fact(
            case,
            K.FEE,
            f"Before joining October 2026: optional INR {amount} printed certificate; completion is free.",
            mandatory=False,
            disclosed_before_joining=True,
            amount_minor=amount * 100,
            currency="INR",
        )
    elif family == "missing_terms":
        fact(
            case,
            K.FEE,
            f"I received an INR {amount} request after completion. My joining terms are unavailable.",
            mandatory=None,
            amount_minor=amount * 100,
            currency="INR",
            attribution="participant_reported",
        )
    elif family == "mentorship":
        fact(case, K.MENTOR_PROMISE, "October 2026 includes weekly review by a mentor.")
        fact(
            case,
            K.MENTOR_DENIAL,
            "In October 2026 my mentor never reviewed the submitted project.",
            attribution="participant_reported",
        )
    elif family in ("unpaid_due", "unpaid_unknown"):
        fact(
            case,
            K.UNPAID,
            "I report that the agreed stipend was not received by 2026-09-01.",
            due_date=date(2026, 9, 1) if family == "unpaid_due" else None,
            attribution="participant_reported",
        )
    else:
        kind, quote = {
            "tasks": (K.TASKS, "Every learner receives the same dashboard task sheet."),
            "conditional": (
                K.CONDITIONAL,
                "Earn up to INR 15000 after meeting the disclosed sales target.",
            ),
            "partner": (K.PARTNER, "Our technology partner supports the course platform."),
            "training": (
                K.TRAINING,
                "This is unpaid simulated training, with no promise of employment.",
            ),
            "sensitive": (K.SENSITIVE, "Send your account password and OTP to release earnings."),
            "authority": (
                K.AUTHORITY,
                "The agency sender differs from the advertised employer; authorization has not been supplied.",
            ),
            "referral_hidden": (
                K.REFERRAL,
                "The mandatory referral requirement was first disclosed after joining.",
            ),
            "promotion_hidden": (
                K.PROMOTION,
                "A mandatory promotional post is newly required to receive the certificate.",
            ),
            "pressure": (
                K.PRESSURE,
                "You must decide immediately; no time is offered to review the agreement.",
            ),
            "business_test": (
                K.WORK,
                "The unpaid test requests three finished business deliverables for customer use.",
            ),
            "changed_terms": (
                K.CHANGE,
                "The later document changes the agreed completion requirements.",
            ),
        }[family]
        fields = (
            {"mandatory": True, "disclosed_before_joining": False}
            if family in ("referral_hidden", "promotion_hidden")
            else {}
        )
        fact(case, kind, f"Case variant {variant + 1}. " + quote, **fields)
    return case


def main():
    manifest = {
        "version": 1,
        "type": "pre-extracted fictional rule-regression facts",
        "human_reviewers": 0,
        "families": FAMILIES,
        "files": {},
    }
    for split, families in FAMILIES.items():
        folder = ROOT / "fixtures" / "synthetic" / split
        folder.mkdir(parents=True, exist_ok=True)
        for family in families:
            for variant in range(3):
                case = build(family, variant)
                payload = {
                    "provenance": "Author-created synthetic ground truth; not real evidence",
                    "family": family,
                    "expected_rules": EXPECTED[family],
                    "case": case.model_dump(mode="json"),
                }
                text = json.dumps(payload, ensure_ascii=False, indent=2)
                path = folder / f"{family}-{variant + 1}.json"
                path.write_text(text, encoding="utf-8")
                manifest["files"][path.relative_to(ROOT).as_posix()] = hashlib.sha256(
                    text.encode()
                ).hexdigest()
    (ROOT / "fixtures" / "synthetic" / "manifest.json").write_text(
        json.dumps(manifest, indent=2), encoding="utf-8"
    )
    print("Wrote 60 fictional regression cases, grouped into 30 development / 30 heldout.")


if __name__ == "__main__":
    main()
